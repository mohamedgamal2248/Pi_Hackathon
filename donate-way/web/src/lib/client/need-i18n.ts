const dicts = { ar, en } as const;

export function nt(lang: Lang, key: NeedKey, vars?: Record<string, string | number>): string {
  let s: string = dicts[lang][key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

// Server error code -> friendly text (falls back to the generic message).
export function needError(lang: Lang, code: string, generic: string): string {
  const key = `e_${code}` as NeedKey;
  return key in ar ? nt(lang, key) : `${generic} (${code})`;
}
