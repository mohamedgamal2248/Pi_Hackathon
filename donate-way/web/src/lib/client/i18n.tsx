export type Lang = "ar" | "en";
const dicts: Record<Lang, Dict> = { ar, en };

type Ctx = { lang: Lang; t: (k: TKey, vars?: Record<string, string | number>) => string; setLang: (l: Lang) => void };
const LangContext = createContext<Ctx>({ lang: "ar", t: (k) => ar[k], setLang: () => {} });

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("ar");

  useEffect(() => {
    try {
      const saved = localStorage.getItem("sanad_lang");
      // First visit: follow the device language (Arabic devices get Arabic, everyone else English).
      const device = (navigator.languages?.[0] ?? navigator.language ?? "").toLowerCase().startsWith("ar") ? "ar" : "en";
      // eslint-disable-next-line react-hooks/set-state-in-effect -- restore saved preference after hydration
      setLangState(saved === "en" || saved === "ar" ? saved : device);
    } catch {}
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("sanad_lang", l);
    } catch {}
  }, []);

  const t = useCallback(
    (k: TKey, vars?: Record<string, string | number>) => {
      let s = dicts[lang][k] ?? k;
      if (vars) for (const [name, v] of Object.entries(vars)) s = s.replace(`{${name}}`, String(v));
      return s;
    },
    [lang]
  );
  return <LangContext.Provider value={{ lang, t, setLang }}>{children}</LangContext.Provider>;
}

export const useLang = () => useContext(LangContext);
