export type Lang = "ar" | "en";
const dicts: Record<Lang, Dict> = { ar, en };

type Ctx = { lang: Lang; t: (k: TKey) => string; toggle: () => void };
const LangContext = createContext<Ctx>({ lang: "ar", t: (k) => ar[k], toggle: () => {} });

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>("ar");

  useEffect(() => {
    try {
      const saved = localStorage.getItem("dw_lang");
      // eslint-disable-next-line react-hooks/set-state-in-effect -- restore saved preference after hydration
      if (saved === "en" || saved === "ar") setLang(saved);
    } catch {}
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);

  const toggle = useCallback(() => {
    setLang((l) => {
      const next = l === "ar" ? "en" : "ar";
      try {
        localStorage.setItem("dw_lang", next);
      } catch {}
      return next;
    });
  }, []);

  const t = useCallback((k: TKey) => dicts[lang][k], [lang]);
  return <LangContext.Provider value={{ lang, t, toggle }}>{children}</LangContext.Provider>;
}

export const useLang = () => useContext(LangContext);
